let current: Texts = de;
let currentLang = 'de';

/** @param lang - language: de, or en for all others */
export function setLanguage(lang: string): void {
    currentLang = lang;
    current = lang === 'de' ? de : en;
}

/** @returns the system language */
export function language(): string {
    return currentLang;
}

/**
 * Translates a key, `{name}` is replaced by `args.name`
 *
 * @param key - text key
 * @param args - replacements
 */
export function t(key: keyof Texts, args: Record<string, string | number> = {}): string {
    return current[key].replace(/\{(\w+)\}/g, (_, k: string) => String(args[k] ?? ''));
}

/** Text key */
export type TextKey = keyof Texts;
